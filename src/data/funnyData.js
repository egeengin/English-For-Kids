export function getNextCyclicIndex(current, length) {
  if (!Number.isFinite(length) || length <= 0) return 0;
  return (Math.max(0, Number(current) || 0) + 1) % length;
}

export function getRandomSillyIndices(rng = Math.random) {
  return {
    s: Math.floor(rng() * SILLY_SENTENCE_PARTS.subjects.length),
    v: Math.floor(rng() * SILLY_SENTENCE_PARTS.verbs.length),
    o: Math.floor(rng() * SILLY_SENTENCE_PARTS.objects.length),
    p: Math.floor(rng() * SILLY_SENTENCE_PARTS.places.length),
  };
}

export function buildSillySentence(indices = { s: 0, v: 0, o: 0, p: 0 }) {
  const s = SILLY_SENTENCE_PARTS.subjects[(indices.s || 0) % SILLY_SENTENCE_PARTS.subjects.length];
  const v = SILLY_SENTENCE_PARTS.verbs[(indices.v || 0) % SILLY_SENTENCE_PARTS.verbs.length];
  const o = SILLY_SENTENCE_PARTS.objects[(indices.o || 0) % SILLY_SENTENCE_PARTS.objects.length];
  const p = SILLY_SENTENCE_PARTS.places[(indices.p || 0) % SILLY_SENTENCE_PARTS.places.length];

  const parts = [s.text, v.text, o.text, p.text];
  return {
    slots: { s, v, o, p },
    parts,
    fullText: parts.join(' '),
    emojis: `${s.emoji} ${v.emoji} ${o.emoji} ${p.emoji}`,
  };
}

export function getFunnyLineByIndex(list = [], idx = 0) {
  if (!Array.isArray(list) || list.length === 0) return '';
  const safeIdx = Math.abs(Math.floor(Number(idx) || 0)) % list.length;
  return list[safeIdx];
}
